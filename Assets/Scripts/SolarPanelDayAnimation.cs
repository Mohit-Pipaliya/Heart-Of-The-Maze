using UnityEngine;

[DisallowMultipleComponent]
public class SolarPanelDayAnimation : MonoBehaviour
{
    [SerializeField] private DayNightController dayNightController;
    [SerializeField] private Animator panelAnimator;
    [Header("Sun Tracking")]
    [Tooltip("Rotating parent of the animated panel. Keep the Animator on a child so its animation does not overwrite tracking rotation.")]
    [SerializeField] private Transform trackingPivot;
    [Tooltip("Panel's local surface normal. Common values are Up or Forward; adjust to match the model.")]
    [SerializeField] private Vector3 localPanelNormal = Vector3.up;
    [Tooltip("If enabled, the panel tilts up/down to face the sun. Disable to track only horizontal sun direction.")]
    [SerializeField] private bool trackSunElevation = true;
    [SerializeField, Min(1f)] private float trackingSpeed = 90f;

    private float _dayAnimationSpeed;
    private bool _isDay;

    private void Awake()
    {
        if (dayNightController == null)
            dayNightController = FindFirstObjectByType<DayNightController>();

        if (panelAnimator == null)
            panelAnimator = GetComponentInChildren<Animator>();

        if (trackingPivot == null)
            trackingPivot = transform;

        if (dayNightController == null)
        {
            Debug.LogError($"[{nameof(SolarPanelDayAnimation)}] Assign a DayNightController or add one to the scene.", this);
            enabled = false;
            return;
        }

        if (panelAnimator == null)
        {
            Debug.LogError($"[{nameof(SolarPanelDayAnimation)}] Assign the solar panel Animator.", this);
            enabled = false;
            return;
        }

        _dayAnimationSpeed = panelAnimator.speed;
        _isDay = dayNightController.IsDay;
        ApplyDayState();

        if (dayNightController.SunTransform == null)
            Debug.LogWarning($"[{nameof(SolarPanelDayAnimation)}] No Sun Transform is assigned or generated by DayNightController; panel tracking will wait for it.", this);
    }

    private void Update()
    {
        if (_isDay == dayNightController.IsDay)
            return;

        _isDay = dayNightController.IsDay;
        ApplyDayState();
    }

    private void LateUpdate()
    {
        // DayNightController moves the sun in Update; LateUpdate makes sure we aim
        // at its current-frame position rather than the previous frame's position.
        if (_isDay)
            TrackSun();
    }

    private void ApplyDayState()
    {
        panelAnimator.speed = _isDay ? _dayAnimationSpeed : 0f;
    }

    private void TrackSun()
    {
        Transform sun = dayNightController.SunTransform;
        if (sun == null || trackingPivot == null || localPanelNormal.sqrMagnitude < 0.0001f)
            return;

        Vector3 direction = sun.position - trackingPivot.position;
        if (!trackSunElevation)
            direction.y = 0f;
        if (direction.sqrMagnitude < 0.0001f)
            return;

        direction.Normalize();
        Transform panelTransform = panelAnimator != null ? panelAnimator.transform : trackingPivot;
        Vector3 currentNormal = panelTransform.TransformDirection(localPanelNormal.normalized);
        Quaternion correction = Quaternion.FromToRotation(currentNormal, direction);
        Quaternion targetRotation = correction * trackingPivot.rotation;
        trackingPivot.rotation = Quaternion.RotateTowards(
            trackingPivot.rotation,
            targetRotation,
            trackingSpeed * Time.deltaTime);
    }
}
